export type ItemCategory =
  | 'tool'
  | 'foreground'
  | 'background'
  | 'seed'
  | 'interactive'
  | 'lock'
  | 'wearable';

export type CollisionType = 'none' | 'solid' | 'platform';

export type ItemRarity = 'common' | 'uncommon' | 'rare' | 'epic';

export type WearableSlot = 'head' | 'face' | 'back';

export interface DropEntry {
  itemId: number;
  chance: number; // 0..1
  minQty: number;
  maxQty: number;
}

export interface ItemDefinition {
  id: number;
  key: string;
  name: string;
  description: string;
  category: ItemCategory;
  rarity: ItemRarity;
  stackLimit: number;
  collision: CollisionType;
  breakable: boolean;
  hardness: number; // hits with base fist
  placeable: boolean;
  tradeable: boolean;
  gemValue: number; // max gems rolled on break
  xpValue: number;
  storePrice?: number; // gem store price
  producesTileId?: number; // for seeds -> resulting tree/block yield
  growthTimeMs?: number; // for seeds
  seedId?: number; // for blocks -> matching seed
  wearableSlot?: WearableSlot;
  lockRadius?: number; // 0 = whole world, >0 = area radius
  drops?: DropEntry[];
  colorPrimary: string;
  colorSecondary: string;
  colorAccent: string;
}

